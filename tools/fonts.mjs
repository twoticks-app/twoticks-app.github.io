// Downloads the IBM Plex fonts the site uses (SIL Open Font License 1.1, see licenses/ibm-plex-OFL.txt) once and
// writes them into src/fonts/ with src/fonts.css, so the published site loads no font from another server.
// One family name, "Plex", covers all twelve languages: it joins the scripts' own Plex families by unicode-range, so
// a page downloads only the files its letters need. Latin and Cyrillic come from the variable IBM Plex Sans (weights
// 400 to 700, widths 85 to 100 percent: the headings use its condensed width), Arabic from IBM Plex Sans Arabic and
// Devanagari from IBM Plex Sans Devanagari. "Plex Mono" is for the one address people copy and the checksum.
// Usage: node tools/fonts.mjs   (needs network access once; the files are then part of the repository)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'src', 'fonts');
// A current Chrome user agent makes Google serve woff2 files split by unicode-range.
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/140.0.0.0 Safari/537.36';

// [our family, Google family, axes as the css2 API takes them, weights to expect, subsets to keep]
const PLAN = [
  ['Plex', 'IBM Plex Sans', 'wdth,wght@85..100,400..700', ['400 700'], ['latin', 'latin-ext', 'cyrillic']],
  ['Plex', 'IBM Plex Sans Arabic', 'wght@400;600;700', ['400', '600', '700'], ['arabic']],
  ['Plex', 'IBM Plex Sans Devanagari', 'wght@400;600;700', ['400', '600', '700'], ['devanagari']],
  ['Plex Mono', 'IBM Plex Mono', 'wght@400', ['400'], ['latin']],
];

const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-');

const faces = [];
const files = [];
// Variable families answer several weights with one file: each file is saved once, and the faces of every weight
// point to it, so a browser downloads it once.
const saved = new Map();
fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT, { recursive: true });
for (const [family, google, axes, weights, keep] of PLAN) {
  const url = `https://fonts.googleapis.com/css2?family=${encodeURIComponent(google).replace(/%20/g, '+')}:${axes}&display=swap`;
  const css = await (await fetch(url, { headers: { 'user-agent': UA } })).text();
  const found = new Set();
  for (const [, subset, body] of css.matchAll(/\/\* ([a-z-]+) \*\/\s*@font-face \{([^}]+)\}/g)) {
    if (!keep.includes(subset)) continue;
    const weight = body.match(/font-weight:\s*([\d ]+);/)[1].trim();
    const stretch = (body.match(/font-stretch:\s*([^;]+);/) || [])[1];
    const range = body.match(/unicode-range:\s*([^;]+);/)[1].trim();
    const src = body.match(/url\((https:[^)]+)\)/)[1];
    let name = saved.get(src);
    if (!name) {
      const font = Buffer.from(await (await fetch(src)).arrayBuffer());
      if (font.toString('latin1', 0, 4) !== 'wOF2') throw new Error(`Not a woff2 file: ${src}`);
      name = `${slug(google)}-${slug(weight)}-${subset}.woff2`;
      fs.writeFileSync(path.join(OUT, name), font);
      files.push([name, font.length]);
      saved.set(src, name);
    }
    found.add(`${weight}/${subset}`);
    faces.push(`@font-face { font-family: "${family}"; font-style: normal; font-weight: ${weight};${stretch && stretch !== '100%' ? ` font-stretch: ${stretch};` : ''} font-display: swap; src: url("fonts/${name}") format("woff2"); unicode-range: ${range}; }`);
  }
  for (const w of weights) for (const s of keep) if (!found.has(`${w}/${s}`)) throw new Error(`${google} ${w} has no ${s} subset`);
}
fs.writeFileSync(
  path.join(ROOT, 'src', 'fonts.css'),
  `/* IBM Plex (SIL Open Font License 1.1, licenses/ibm-plex-OFL.txt). Generated by tools/fonts.mjs: do not edit. */\n${faces.join('\n')}\n`,
);
const total = files.reduce((a, [, n]) => a + n, 0);
console.log(`${files.length} files, ${Math.round(total / 1024)} KB in src/fonts`);
for (const [n, s] of files) console.log(`  ${n}  ${Math.round(s / 1024)} KB`);
